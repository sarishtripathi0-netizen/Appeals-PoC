import { formatDate } from "@/domain/dates";
import { penaltyMachine, type PenaltyStatus } from "@/domain/penalty-machine";
import { monthName } from "@/domain/recovery";
import { statementCsv, statementTotals, type StatementRow } from "@/domain/statement";
import { getSettings } from "@/lib/context";
import { parseJson, prisma } from "@/lib/db";
import { buildPdf, pdfResponse } from "@/lib/pdf";
import { getSessionUser } from "@/lib/session";
import { STATEMENT_VIEWERS } from "@/services/reconciliation";

const label = (s: string) => penaltyMachine.statusLabels[s as PenaltyStatus] ?? s;
const rs = (n: number) => `Rs. ${n.toLocaleString("en-IN")}`;

export async function GET(req: Request, { params }: { params: Promise<{ month: string }> }) {
  const u = await getSessionUser();
  if (!u) return new Response("Please sign in.", { status: 401 });
  if (!STATEMENT_VIEWERS.includes(u.role)) return new Response("Not found.", { status: 404 });
  const { month } = await params;
  const st = await prisma.monthlyStatement.findUnique({ where: { month } });
  if (!st) return new Response("Not found.", { status: 404 });
  const rows = parseJson<StatementRow[]>(st.rows, []);
  const format = new URL(req.url).searchParams.get("format");

  if (format === "csv") {
    return new Response(statementCsv(rows, label), {
      headers: { "Content-Type": "text/csv; charset=utf-8", "Content-Disposition": `attachment; filename="penalty-statement-${month}.csv"` },
    });
  }
  const s = await getSettings();
  const t = statementTotals(rows);
  const pdf = await buildPdf({
    title: `Penalty statement: ${monthName(month)}`,
    subtitle: `Penalties under the Assam Right to Public Services Act. Head of account ${s.headOfAccount}. Generated ${formatDate(st.generatedOn, true)}.`,
    sections: [
      {
        heading: "Totals",
        rows: [
          ["Penalties", String(t.penalties)], ["Imposed", rs(t.imposed)], ["Collected through eGRAS", rs(t.egras)], ["Deducted from salary", rs(t.deducted)],
          ["Credited to the head of account", rs(t.credited)], ["Refunded", rs(t.refunded)], ["Written off", rs(t.writtenOff)],
          ["Collected but not credited", rs(t.difference)], ["Outstanding", rs(t.outstanding)],
        ],
      },
      {
        heading: "By penalty",
        paragraphs: rows.map((r) =>
          `${r.ref} (${r.uin}), ${r.officerName}, ${r.employeeId}: imposed ${rs(r.imposed)}; eGRAS ${rs(r.egras)}${r.grns.length ? ` [${r.grns.join(", ")}]` : ""}; salary ${rs(r.deducted)}${r.vouchers.length ? ` [${r.vouchers.join(", ")}]` : ""}; credited ${rs(r.credited)}; refunded ${rs(r.refunded)}; written off ${rs(r.writtenOff)}; difference ${rs(r.difference)}; outstanding ${rs(r.outstanding)}. ${label(r.status)}.`),
      },
    ],
    footer: `Central recovery under: ${s.centralRecoveryNotificationRef}. Generated by the Sewa Setu proof of concept; names and figures are fictional.`,
  });
  return pdfResponse(pdf, `penalty-statement-${month}.pdf`);
}
